-- Inserting rows

-- | Insert the rows into the table, one value per insertable column
-- ('InsertableColumns'), and return how many rows the server inserted.
-- @'bulkInsertWith' ('bulkCopy' table)@.
--
-- > bulkInsert conn "dbo.item" [(1 :: Int32, "one" :: Text), (2, "two")]
bulkInsert :: ToSqlRow r => Connection -> Text -> [r] -> IO Int64
bulkInsert conn table = bulkInsertWith (bulkCopy table) conn
-- Out of line: inlined, each use built its own 'BulkCopy' of the defaults, and a
-- function calling 'bulkInsert' was 527 bytes of object code instead of 327.
{-# NOINLINE bulkInsert #-}

-- | 'bulkInsert' with the settings.
--
-- > bulkInsertWith (bulkCopy "dbo.item") { bulkColumns = NamedColumns ["id", "name"], bulkTableLock = True } conn rows
bulkInsertWith :: ToSqlRow r => BulkCopy -> Connection -> [r] -> IO Int64
bulkInsertWith bc conn rows = bulkInsertSWith bc conn (S.each rows)
{-# NOINLINE bulkInsertWith #-}

-- | 'bulkInsert' with rows from a stream and the default settings.
-- Use 'bulkInsertSWith' to choose columns, batching or other options.
-- The streaming and interruption rules of 'bulkInsertSWith' apply.
--
-- > bulkInsertS conn "dbo.item" rows
bulkInsertS :: ToSqlRow r => Connection -> Text -> Stream (Of r) IO () -> IO Int64
bulkInsertS conn table = bulkInsertSWith (bulkCopy table) conn
{-# NOINLINE bulkInsertS #-}

-- | 'bulkInsertWith' with the rows from a stream, read as they are sent:
-- a packet's worth at a time, so a stream of any length needs no more
-- memory than that.
--
-- The stream runs while the request is being sent, with the connection
-- locked: it must not use this connection (stream the rows from another
-- one; on a MARS connection it may read a stream opened on this one
-- before the load began, but not start a request).  If it throws, the
-- load is canceled and the exception is rethrown. Earlier batches stay
-- committed. Cancellation normally leaves the connection usable, but the
-- server can close it for an incomplete large bulk message. A row whose
-- values can't be converted throws 'EncodeError' the same way, naming
-- the row (from 0) and the column.  An asynchronous exception (a
-- 'System.Timeout.timeout' expiring) while the rows are being sent
-- breaks the connection instead, as an interrupted send does for any
-- request.
--
-- With 'bulkBatchSize', each batch is sent and its response read before
-- the next batch's rows are pulled from the stream.  An empty stream
-- sends nothing and returns 0.
--
-- The usual source is a query on another connection, which copies a
-- table of any size a packet at a time:
--
-- > src <- queryS source "SELECT id, name, price FROM dbo.item WHERE price > 1"
-- > n <- bulkInsertS target "dbo.expensive_item" (src :: Stream (Of (Int, Text, Decimal)) IO ())
bulkInsertSWith :: forall r. ToSqlRow r => BulkCopy -> Connection -> Stream (Of r) IO () -> IO Int64
bulkInsertSWith bc conn rows0 = withReservedSession conn $ do
  batchSize <- case bulkBatchSize bc of
    Just n | n < 1 -> throwIO $ EncodeError $ "bulk copy: bulkBatchSize " ++ show n ++ " (at least 1, or Nothing)"
    b -> pure b
  cols <- describeBulkColumns conn bc
  when (null cols) $ throwIO $ EncodeError $ "bulk copy: " ++ T.unpack (bulkTable bc) ++ " has no column to insert"
  ctx <- connectionContext conn
  let convert = compileRow ctx cols :: r -> Either String [ParamValue]
      -- Out of line, so that the message is built only when a row fails.
      -- Inlined at its two uses, GHC shared the @show i@ between them as a
      -- thunk allocated on every row's success path: 23,976 bytes per load of
      -- 1,000 rows (GHC 9.12.4, 2026-11-04).
      {-# NOINLINE rowProblem #-}
      rowProblem i msg = EncodeError $ "bulk copy: row " ++ show i ++ " (from 0), " ++ msg

      -- One batch: the first row (converted already), then the rest of
      -- the stream, or as many of it as the batch takes; the count, the
      -- index of the next row, and the stream after the batch.
      loadBatch :: Int -> [ParamValue] -> Stream (Of r) IO x -> IO (Int64, Int, x)
      loadBatch i0 firstCells s0 = do
        -- The first row decides the layout.  @nchar@, @nvarchar@, @binary@ and
        -- @varbinary@ aren't PLP on the wire, so a stream in the first row makes
        -- its column @(max)@ for this batch; 'checkStreams' refuses a stream in a
        -- later row of a column that didn't.  A stream can't be measured ahead, so
        -- an over-long value is left to the server.  With ANSI_WARNINGS ON it
        -- refuses the load (error 2628); with it OFF it truncates, as an INSERT does.
        let layout = zipWith (\col value -> (if streamed value then promote else id) (bulkWireType (bulkColumnType col))) cols firstCells
            wireCols = zipWith (\col ti -> col { bulkColumnType = ti }) cols layout
            stmt = insertBulkStatement bc wireCols
            meta = colMetaData (bulkTable bc) wireCols
            checkStreams i values = when (any streamed values) $ forM_ (zip3 cols layout values) $ \(col, ti, value) ->
              when (streamed value && not (isPlp ti)) $ throwIO (rowProblem i ("column " ++ T.unpack (bulkColumnName col) ++ ": the first row did not select a streaming wire type"))
        _ <- execute conn (rawSql stmt)
        after <- newIORef Nothing
        -- Masked from the send to the guard on the response (the producer
        -- runs masked anyway, 'startStreamingRequest').
        n <- mask $ \restore -> do
          ar <- startStreamingRequest conn (Just stmt) PTBulkLoad $ \out -> do
            writeBytes out meta
            writeRow out layout firstCells
            -- One guard around the whole batch: pulling a row may run the caller's
            -- stream, which must not start a request on this connection.  Taking
            -- it per row would cost a mask and a bracket per row, inside a send
            -- that is already masked.
            let loop !i s = S.next s >>= \case
                  Left x -> writeIORef after (Just (i, x))
                  Right (row, s') -> do
                    cells <- either (throwIO . rowProblem i) pure (convert row)
                    checkStreams i cells
                    writeRow out layout cells
                    loop (i + 1) s'
            sourceAction conn (loop (i0 + 1) s0)
            writeBytes out doneToken
          readingToEnd conn ar (restore (responseReader conn ar (Just stmt) >>= affectedRows))
        readIORef after >>= \case
          Just (i, x) -> pure (n, i, x)
          Nothing -> throwIO $ ProtocolError "bulk copy: the rows were not all sent"  -- can't happen: the producer completed

      go !total !i s = sourceAction conn (S.next s) >>= \case
        Left () -> pure total
        Right (first, rest) -> do
          cells <- either (throwIO . rowProblem i) pure (convert first)
          case batchSize of
            Nothing -> do
              (n, _, ()) <- loadBatch i cells rest
              pure (total + n)
            Just k -> do
              (n, i', rest') <- loadBatch i cells (S.splitAt (k - 1) rest)
              go (total + n) i' rest'
  go 0 (0 :: Int) rows0
  where
    promote (TINChar _ c) = TINVarChar maxLength c
    promote (TINVarChar _ c) = TINVarChar maxLength c
    promote (TIBigBinary _) = TIBigVarBinary maxLength
    promote (TIBigVarBinary _) = TIBigVarBinary maxLength
    promote ti = ti
    isPlp ti = case lengthKind ti of Plp -> True; _ -> False

