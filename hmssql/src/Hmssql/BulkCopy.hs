-- | The converter of a row: each value encoded by its 'Hmssql.Encoding.ToSqlField'
-- instance, then converted to its column ('encodeBulkCell').  Positional
-- values go to the columns in order; named ones ('Hmssql.Encoding.NamedParams') to the
-- columns of their names, with the one leading @\@@ 'Hmssql.Encoding.NamedParams' puts
-- before a name removed: an exact match first, else a case-insensitive
-- one when it matches one column and one value, since a catalog can be
-- case-sensitive (@a@ beside @A@).  A problem names the column.
compileRow :: forall r. ToSqlRow r => TdsContext -> [BulkColumn] -> r -> Either String [ParamValue]
compileRow ctx cols = \r -> convertRow (encodeParams enc r)
  where
    enc = rowEncoder :: RowEncoder r
    n = length cols
    converters = [(c, encodeBulkCell ctx c) | c <- cols]
    foldedColumnNames = map (T.toCaseFold . bulkColumnName) cols
    normalizeName name = fromMaybe name (T.stripPrefix "@" name)
    convertRow params
      | any (not . T.null . fst) params = byName params
      | otherwise = positional converters params
      where
        positional [] [] = Right []
        positional ((c, conv) : cs) ((_, e) : ps) = do
          v <- inColumn c (e ctx >>= conv)
          (v :) <$> positional cs ps
        positional _ _ = Left $ "the row has " ++ show (length params) ++ " values for " ++ show n ++ " columns"
    byName params = do
      given <- forM params $ \(name, e) ->
        if T.null name
          then Left "the row mixes named and positional values"
          else Right (normalizeName name, e)
      unless (length given == n) $
        Left $ "the row has " ++ show (length given) ++ " values for " ++ show n ++ " columns"
      forM converters $ \(c, conv) -> inColumn c $ do
        e <- namedValue (bulkColumnName c) given
        e ctx >>= conv
    namedValue name given = case [e | (n, e) <- given, n == name] of
      [e] -> Right e
      [] ->
        let folded = T.toCaseFold name
         in if length (filter (== folded) foldedColumnNames) > 1
              then Left $ "ambiguous column name " ++ show name ++ "; use its exact spelling"
              else case [e | (n, e) <- given, T.toCaseFold n == folded] of
                [e] -> Right e
                [] -> Left $ "no value named " ++ show name
                _ -> Left $ "more than one value matches column " ++ show name
      _ -> Left $ "more than one value named " ++ show name
    inColumn c = either (\m -> Left ("column " ++ T.unpack (bulkColumnName c) ++ ": " ++ m)) Right

-- | Encode a value for a bulk load into this column: its bytes in the wire
-- type the column is sent as (@'bulkWireType' ('bulkColumnType' column)@), or
-- why the column can't take the value.  The column's own type supplies the
-- checks, and the wire type may differ: a @varchar@ column's value is checked
-- against the column's length and code page, then sent as UTF-16 in
-- @nvarchar(max)@ for the server to transcode.
--
-- A NULL is sent as NULL to a nullable column and refused for a NOT NULL one.
-- A value's framing is checked as an ordinary parameter's is
-- ('Hmssql.Tds.TypeInfo.valueProblem'), so an empty numeric or @sql_variant@
-- payload can't become a NULL by accident, and a value declared as a fixed
-- @char@, @nchar@ or @binary@ is padded to its length before conversion, as
-- an RPC parameter is.  Where the column's type and its wire type agree, a
-- value already in that type (an 'Int32' for an @int@ column, a 'Text' that
-- fits an @nvarchar@ column, or a matching 'Hmssql.Encoding.RawParam') is sent as it is.  A
-- value converted to @sql_variant@ keeps its declared base type, precision,
-- scale, length and collation, with its bytes as they are.  Other conversions
-- decode the value and encode it again:
--
-- * Integers, 'Bool', 'Decimal', 'Double', 'Float' and 'Money' to any of
--   @bit@ (nonzero is 1), the integer types (fractions truncate toward
--   zero, except 'Money', which rounds half away from zero), @decimal@ and @numeric@
--   (rounded to the column's scale, half away from zero, a floating-point
--   value from its exact binary value), @float@,
--   @real@, @money@ and @smallmoney@ (rounded to four places); a value
--   outside the column's range is refused. Nonfinite floating sources are
--   refused for @bit@ rather than converted to true.
-- * 'Text' (and 'String') to @nchar@, @nvarchar@, @ntext@
--   (as UTF-16), @char@, @varchar@, @text@ (validated against the column's
--   UTF-8 or single-byte code page, then sent as UTF-16; a character the
--   page lacks is refused), @xml@ and @sql_variant@ (as @nvarchar@, in the
--   session's collation). A string longer than the column is refused.
--   'SqlXml' goes to character and @xml@ columns too.  A character column
--   gets its text as it is, without the server's XML canonicalization, and
--   raw XML bytes in an encoding other than UTF-8 or a UTF-16 the client can
--   identify are refused there.
-- * 'Data.ByteString.ByteString' to @binary@, @varbinary@, @image@ and @sql_variant@;
--   longer than the column, refused.
-- * 'Day', 'TimeOfDay', 'LocalTime', 'UTCTime', 'DateTimeOffset' and
--   'ZonedTime' to @date@, @time@, @datetime2@, @datetimeoffset@ (at the
--   column's scale, rounded as the 'Hmssql.Encoding.ToSqlField' instances round),
--   @datetime@ and @smalldatetime@: a date at midnight, the date or time
--   part of a date-time, a @datetimeoffset@'s local time, a date-time
--   with offset zero.
-- * 'Data.UUID.Types.UUID' to @uniqueidentifier@ only; every value but 'SqlXml' to
--   @sql_variant@.
--
-- Anything else (a 'Text' for an @int@ column, a number for a string
-- column, a CLR type) is refused: convert it in Haskell, or declare the
-- column ('DescribedColumns') with the type the value is sent as and let
-- the server convert.
encodeBulkCell :: TdsContext -> BulkColumn -> EncodedParam -> Either String ParamValue
encodeBulkCell ctx col (source, ParamBytes v) = ParamBytes <$> encodeBulkBytes ctx col (source, v)
-- A lazy or streamed value: its bytes can't be checked ahead, so only its
-- encoding is checked here.  The wire is UTF-16 for a character column, so a
-- @varchar(max)@ source is refused rather than transcoded.  A text source into
-- @xml@ gets a byte order mark, so that the server reads it as UTF-16.
encodeBulkCell _ col (source, value) = do
  mapM_ Left (paramValueProblem source value)
  case bulkWireType (bulkColumnType col) of
    TINChar{} | unicode source -> Right value
    TINVarChar{} | unicode source -> Right value
    TIBigBinary{} | binary source -> Right value
    TIBigVarBinary{} | binary source || xml source -> Right value
    TIBigVarBinary{} | isXmlTarget && unicode source -> Right (bom value)
    _ -> Left "stream type is incompatible with the bulk column's wire encoding"
  where
    unicode TINVarChar{} = True
    unicode _ = False
    binary TIBigVarBinary{} = True
    binary _ = False
    xml TIXml{} = True
    xml _ = False
    isXmlTarget = case bulkColumnType col of TIXml{} -> True; _ -> False
    bom (ParamLazy bs) = ParamLazy (LB.fromStrict "\xFF\xFE" <> bs)
    bom (ParamStream (Source sourceOfBytes)) = ParamStream (Source (\use -> sourceOfBytes (\s -> use (S.yield "\xFF\xFE" >> s))))
    bom bytes = bytes

-- | 'encodeBulkCell' for a value in memory, whose length and code page can be
-- checked before anything is sent.
encodeBulkBytes :: TdsContext -> BulkColumn -> (TypeInfo, RawBytes) -> Either String RawBytes
encodeBulkBytes ctx col (source, v) = case v of
  Nothing
    | bulkColumnNullable col -> Right Nothing
    | otherwise -> Left "NULL, but the column is NOT NULL"
  Just raw -> do
    mapM_ Left (valueProblem source (Just raw))
    let bs = padFixedSource source raw
    Just <$> (if wire == real then asIs bs else remapped bs)
  where
    real = bulkColumnType col
    wire = bulkWireType real
    -- The column's values are sent as themselves (the common case).
    asIs bs
      | sameStorage real source bs = Right bs
      | TISqlVariant _ <- real = variantFromSource ctx source bs
      | otherwise = sourceValue source bs >>= encodeValueAs ctx real
    -- A column sent in a different wire type ('bulkWireType'): a character
    -- column as UTF-16, or an image/XML column as varbinary. The value
    -- is validated against the /real/ type first (a character absent from
    -- the column's code page, or a value too long, is refused here, not
    -- silently transcoded or truncated by the server), then written in the
    -- wire type.
    remapped bs = case real of
      -- XML's own parser interprets its declared byte encoding. Sending
      -- it through nvarchar makes unmarked UTF-8 look like UTF-16 text.
      TIXml _ -> case source of
        TIXml _ -> Right bs
        _ | isUnicode source -> Right (xmlUnicode bs)
        _ | Just coll <- ansiCollation source
          , collationCodePage coll == Just 65001 || hasXmlBom bs || isJust (xmlDeclaredEncoding bs) -> Right bs
        _ -> xmlUnicode . encodeUtf16LE <$> charText bs
      -- Both source and bulk wire are UTF-16. Passing the original code
      -- units also preserves SQL-accepted lone surrogates; a text decoder
      -- would replace them even though no character conversion is needed.
      TINText _ _ | isUnicode source -> Right bs
      TIImage _ -> case sourceValue source bs of
        Right (SqlBinary b) -> Right b
        Right other -> Left ("cannot copy " ++ describe other ++ " into an image column")
        Left e -> Left e
      _ -> do
        t <- charText bs
        validateChar real t
        Right (encodeUtf16LE t)
    -- Unicode-to-XML conversion assumes UTF-16 only when no byte order
    -- mark selects another encoding. Preserve that server decision.
    xmlUnicode bs
      | hasXmlBom bs = bs
      | otherwise = "\xFF\xFE" <> bs
    hasXmlBom bs = any (`B.isPrefixOf` bs) ["\xFF\xFE","\xFE\xFF","\xEF\xBB\xBF"]
    charText bs = sourceValue source bs >>= \case
      SqlText t -> Right t
      SqlXml t -> Right t
      other -> Left ("cannot copy " ++ describe other ++ " into a character column; convert it in Haskell first")

-- Fixed source declarations carry padding semantics before conversion to
-- another type, just as an RPC parameter does. Variable sources retain
-- their actual length. NULL is handled before this function is called.
padFixedSource :: TypeInfo -> B.ByteString -> B.ByteString
padFixedSource source bs = case source of
  TIBigChar n _ -> padByte (fromIntegral n) 0x20
  TIBigBinary n -> padByte (fromIntegral n) 0
  TINChar n _
    | missing > 0 && even missing -> bs <> B.concat (replicate (missing `div` 2) (B.pack [0x20,0]))
    where missing = fromIntegral n - B.length bs
  _ -> bs
  where
    padByte width byte
      | width > B.length bs = bs <> B.replicate (width - B.length bs) byte
      | otherwise = bs

-- Only inspect the declaration's encoding attribute. XML syntax and charset
-- validation remain with SQL Server; this is not an XML document parser.
xmlDeclaredEncoding :: B.ByteString -> Maybe B.ByteString
xmlDeclaredEncoding bs = do
  guard ("<?xml" `B.isPrefixOf` bs)
  (next, _) <- B.uncons (B.drop 5 bs)
  guard (xmlSpace next)
  let declaration = fst (B.breakSubstring "?>" bs)
      attribute = snd (B.breakSubstring "encoding" declaration)
  afterName <- B.stripPrefix "encoding" attribute
  afterEquals <- B.stripPrefix "=" (B.dropWhile xmlSpace afterName)
  (quote, value) <- B.uncons (B.dropWhile xmlSpace afterEquals)
  guard (quote == 34 || quote == 39)
  let (name, closing) = B.break (== quote) value
  guard (not (B.null closing))
  pure name
  where
    xmlSpace byte = byte `elem` [9,10,13,32]

-- | Check that a 'Text' fits a single-byte @char@\/@varchar@\/@text@
-- column: every character is representable in the column's code page (else
-- the server would store @\'?\'@, losing data) and, for a bounded column,
-- the encoded value is no longer than the column
-- (independent of @SET ANSI_WARNINGS@, which the server's own check
-- depends on).  A collation hmssql can't encode (a double-byte code page,
-- or an unknown one) is left to the server.  @nchar@\/@nvarchar@ (checked
-- by 'encodeValueAs') and @ntext@\/@xml@ (Unicode, no code page) don't
-- come here.
validateChar :: TypeInfo -> Text -> Either String ()
validateChar ti t = case ti of
  TIBigChar n c -> check c (Just (fromIntegral n))
  TIBigVarChar n c
    | n == maxLength -> check c Nothing
    | otherwise -> check c (Just (fromIntegral n))
  TIText _ c -> check c Nothing
  _ -> Right ()
  where
    check coll mlimit = case collationTextEncoder coll of
      Left _ -> Right ()  -- a code page hmssql can't encode: the server enforces it
      Right enc -> case enc t of
        Left err -> Left ("would lose data: " ++ err)
        Right bs -> case mlimit of
          Just n | B.length bs > n -> Left $
            "the value encodes to " ++ show (B.length bs) ++ " bytes; the column "
              ++ T.unpack (typeInfoSqlName ti) ++ " holds " ++ show n
          _ -> Right ()

-- | Whether the value's bytes, in the source type, are already what the
-- target type carries (and fit it).
sameStorage :: TypeInfo -> TypeInfo -> B.ByteString -> Bool
sameStorage target source bs = case (target, source) of
  _ | Just m <- intWidth target, Just n <- intWidth source -> m == n
    | isBit target, isBit source -> True
    | Just m <- floatWidth target, Just n <- floatWidth source -> m == n
    | Just m <- moneyWidth target, Just n <- moneyWidth source -> m == n
    | Just m <- dateTimeWidth target, Just n <- dateTimeWidth source -> m == n
    | Just (p, s) <- decimalOf target, Just (p', s') <- decimalOf source ->
        s == s' && p' <= p && precisionToLength p == precisionToLength p'
    | Just limit <- unicodeLimit target, isUnicode source -> fits limit
    | Just (limit, c) <- ansiLimit target, Just c' <- ansiCollation source ->
        isJust (collationCodePage c) && collationCodePage c == collationCodePage c' && fits limit
    | Just limit <- binaryLimit target, isBinary source -> fits limit
  (TIGuid, TIGuid) -> True
  (TIDateN, TIDateN) -> True
  (TITimeN a, TITimeN b) -> a == b
  (TIDateTime2N a, TIDateTime2N b) -> a == b
  (TIDateTimeOffsetN a, TIDateTimeOffsetN b) -> a == b
  (TIXml _, TIXml _) -> True
  (TISqlVariant _, TISqlVariant _) -> True
  (TIUdt _, TIUdt _) -> True
  _ -> False
  where
    fits limit = limit < 0 || B.length bs <= limit

-- Type families, by what the wire carries.

intWidth :: TypeInfo -> Maybe Int
intWidth = \case
  TIInt1 -> Just 1
  TIInt2 -> Just 2
  TIInt4 -> Just 4
  TIInt8 -> Just 8
  TIIntN n -> Just (fromIntegral n)
  _ -> Nothing

isBit :: TypeInfo -> Bool
isBit = \case
  TIBit -> True
  TIBitN -> True
  _ -> False

floatWidth :: TypeInfo -> Maybe Int
floatWidth = \case
  TIFlt4 -> Just 4
  TIFlt8 -> Just 8
  TIFltN n -> Just (fromIntegral n)
  _ -> Nothing

moneyWidth :: TypeInfo -> Maybe Int
moneyWidth = \case
  TIMoney4 -> Just 4
  TIMoney8 -> Just 8
  TIMoneyN n -> Just (fromIntegral n)
  _ -> Nothing

dateTimeWidth :: TypeInfo -> Maybe Int
dateTimeWidth = \case
  TIDateTime4 -> Just 4
  TIDateTime8 -> Just 8
  TIDateTimeN n -> Just (fromIntegral n)
  _ -> Nothing

decimalOf :: TypeInfo -> Maybe (Precision, Scale)
decimalOf = \case
  TIDecimalN p s -> Just (p, s)
  TINumericN p s -> Just (p, s)
  _ -> Nothing

-- | The most bytes a UTF-16 column takes (-1: no limit).
unicodeLimit :: TypeInfo -> Maybe Int
unicodeLimit = \case
  TINChar len _ -> Just (fromIntegral len)
  TINVarChar len _ -> Just (if len == maxLength then -1 else fromIntegral len)
  TINText _ _ -> Just (-1)
  _ -> Nothing

isUnicode :: TypeInfo -> Bool
isUnicode = isJust . unicodeLimit

-- | The most bytes a single-byte column takes, and its collation.
ansiLimit :: TypeInfo -> Maybe (Int, Collation)
ansiLimit = \case
  TIBigChar len c -> Just (fromIntegral len, c)
  TIBigVarChar len c -> Just (if len == maxLength then -1 else fromIntegral len, c)
  TIText _ c -> Just (-1, c)
  _ -> Nothing

ansiCollation :: TypeInfo -> Maybe Collation
ansiCollation = fmap snd . ansiLimit

binaryLimit :: TypeInfo -> Maybe Int
binaryLimit = \case
  TIBigBinary len -> Just (fromIntegral len)
  TIBigVarBinary len -> Just (if len == maxLength then -1 else fromIntegral len)
  TIImage _ -> Just (-1)
  _ -> Nothing

isBinary :: TypeInfo -> Bool
isBinary = isJust . binaryLimit

-- | The value the bytes hold, in the source type.
sourceValue :: TypeInfo -> B.ByteString -> Either String SqlValue
sourceValue ti bs = case ti of
  _ | Just n <- intWidth ti -> case n of
        1 | len == 1 -> Right (SqlWord8 (word8At bs 0))
        2 | len == 2 -> Right (SqlInt16 (int16LeAt bs 0))
        4 | len == 4 -> Right (SqlInt32 (int32LeAt bs 0))
        8 | len == 8 -> Right (SqlInt64 (int64LeAt bs 0))
        _ -> badLength
    | isBit ti -> if len == 1 then Right (SqlBool (word8At bs 0 /= 0)) else badLength
    | Just n <- floatWidth ti -> case n of
        4 | len == 4 -> Right (SqlFloat (castWord32ToFloat (word32LeAt bs 0)))
        8 | len == 8 -> Right (SqlDouble (castWord64ToDouble (word64LeAt bs 0)))
        _ -> badLength
    | Just _ <- moneyWidth ti -> SqlMoney <$> readMoney bs
    | Just n <- dateTimeWidth ti ->
        SqlDateTime <$> (if n == 4 then readDateTime4With localTimeOf else readDateTime8With localTimeOf) bs
    | Just (p, s) <- decimalOf ti -> SqlDecimal <$> readDecimal p s bs
    | isUnicode ti -> Right (SqlText (decodeUtf16LE bs))
    | Just c <- ansiCollation ti -> SqlText <$> (collationTextDecoder c >>= ($ bs))
    | isBinary ti -> Right (SqlBinary bs)
  TIGuid -> SqlGuid <$> readGuid bs
  TIDateN -> SqlDate <$> readDate bs
  TITimeN s -> SqlTime <$> readTime s bs
  TIDateTime2N s -> SqlDateTime <$> readDateTime2 s bs
  TIDateTimeOffsetN s -> SqlDateTimeOffset <$> readDateTimeOffset s bs
  TIXml _ -> SqlXml <$> xmlText bs
  TISqlVariant _ -> Left "a sql_variant value can be copied only into a sql_variant column"
  TIUdt _ -> Left "a CLR user-defined type value can be copied only into a column of its type"
  TINull -> Left "a value of no type"
  _ -> Left ("a value of type " ++ T.unpack (typeInfoSqlName ti) ++ " can't be converted")
  where
    len = B.length bs
    badLength = Left $ "a " ++ T.unpack (typeInfoSqlName ti) ++ " value of " ++ show len ++ " bytes"
    -- SqlXml's normal representation is BOM-marked UTF-16. Raw XML may
    -- instead use UTF-8 or identifiable UTF-16BE. Character destinations retain
    -- lexical text; XML destinations bypass this conversion entirely.
    xmlText b
      | any (`B.isPrefixOf` b) ["\xFF\xFE\0\0","\0\0\xFE\xFF"] =
          Left "XML byte encoding cannot be converted to characters on the client; use Text or an explicit server CONVERT"
      | "\xFF\xFE" `B.isPrefixOf` b = Right (decodeUtf16LE (B.drop 2 b))
      | "\xFE\xFF" `B.isPrefixOf` b = Right (TE.decodeUtf16BEWith lenientDecode (B.drop 2 b))
      | "\xEF\xBB\xBF" `B.isPrefixOf` b = utf8 (B.drop 3 b)
      | "<\0" `B.isPrefixOf` b = Right (decodeUtf16LE b)
      | "\0<" `B.isPrefixOf` b = Right (TE.decodeUtf16BEWith lenientDecode b)
      | Just encoding <- xmlDeclaredEncoding b
      , BC.map toLower encoding `notElem` ["utf-8","utf8","us-ascii"] =
          Left "XML byte encoding cannot be converted to characters on the client; use Text or an explicit server CONVERT"
      | otherwise = utf8 b
      where
        utf8 bytes = case TE.decodeUtf8' bytes of
          Left _ -> Left "XML bytes are not UTF-8; copy into xml or convert to Text explicitly"
          Right text -> Right text

-- | The value encoded for the target type.
{-# NOINLINE encodeValueAs #-}
encodeValueAs :: TdsContext -> TypeInfo -> SqlValue -> Either String B.ByteString
encodeValueAs ctx ti v = case ti of
  _ | Just n <- intWidth ti -> toInt64 v >>= intBytes n
    | isBit ti -> (\b -> B.singleton (if b then 1 else 0)) <$> toBool v
    | Just n <- floatWidth ti -> do
        d <- toDouble v
        when (isNaN d || isInfinite d) $
          Left (describe v ++ " (not a finite number) can't be stored in " ++ T.unpack (typeInfoSqlName ti))
        if n == 4
          then do
            f <- toFloat v
            if isInfinite f
              then Left (describe v ++ " is out of the range of real")
              else Right (littleEndian 4 (fromIntegral (castFloatToWord32 f)))
          else Right (littleEndian 8 (castDoubleToWord64 d))
    | Just n <- moneyWidth ti -> do
        m <- toMoney v
        if n == 4
          then mapM_ Left (money4Problem m) >> put 4 (putMoney4 m)
          else mapM_ Left (money8Problem m) >> put 8 (putMoney8 m)
    | Just n <- dateTimeWidth ti -> do
        lt <- toLocalTime v
        if n == 4 then putDateTime4 lt >>= put 4 else putDateTime8 lt >>= put 8
    | Just (p, s) <- decimalOf ti -> do
        d <- toDecimal s v >>= rescale p s
        put 17 (putDecimal p s d)
    | Just limit <- unicodeLimit ti -> do
        t <- toText v
        let bs = encodeUtf16LE t
        checkLength limit bs "characters" (`div` 2)
    | Just (limit, c) <- ansiLimit ti -> do
        t <- toText v
        encoder <- collationTextEncoder c
        bs <- encoder t
        checkLength limit bs "bytes" id
    | Just limit <- binaryLimit ti -> do
        bs <- toBinary v
        checkLength limit bs "bytes" id
  TIGuid -> case v of
    SqlGuid g -> put 16 (putGuid g)
    _ -> mismatch
  TIDateN -> toDay v >>= putDate >>= put 3
  TITimeN s -> toTimeOfDay v >>= putTime s >>= put 5
  TIDateTime2N s -> toLocalTime v >>= putDateTime2 s >>= put 8
  TIDateTimeOffsetN s -> toDateTimeOffset v >>= putDateTimeOffset s >>= put 10
  TIXml _ -> (\t -> "\xFF\xFE" <> encodeUtf16LE t) <$> toText v
  TISqlVariant _ -> variantOf ctx v
  TIUdt _ -> mismatch
  TINull -> mismatch
  _ -> mismatch
  where
    put :: Int -> Put.Put -> Either String B.ByteString
    put n p = Right (runPutSized n p)
    mismatch = Left $ "cannot copy " ++ describe v ++ " into a " ++ T.unpack (typeInfoSqlName ti)
      ++ " column; convert it in Haskell first"
    checkLength limit bs what units
      | limit >= 0 && B.length bs > limit = Left $
          "the value is " ++ show (units (B.length bs)) ++ " " ++ what ++ " long; the column "
            ++ T.unpack (typeInfoSqlName ti) ++ " holds " ++ show (units limit)
      | otherwise = Right bs

    toInt64 :: SqlValue -> Either String Int64
    toInt64 = \case
      SqlBool b -> Right (if b then 1 else 0)
      SqlWord8 i -> Right (fromIntegral i)
      SqlInt16 i -> Right (fromIntegral i)
      SqlInt32 i -> Right (fromIntegral i)
      SqlInt64 i -> Right i
      SqlDecimal d -> integral (truncate d :: Integer)
      SqlMoney (Money (MkFixed m)) -> integral (signum m * ((abs m + 5000) `div` 10000))
      SqlFloat f -> real (realToFrac f)
      SqlDouble d -> real d
      _ -> mismatch
      where
        integral i
          | i < toInteger (minBound :: Int64) || i > toInteger (maxBound :: Int64) = outOfRange
          | otherwise = Right (fromInteger i)
        real :: Double -> Either String Int64
        real d
          | isNaN d || isInfinite d || d < -9223372036854775808 || d >= 9223372036854775808 = outOfRange
          | otherwise = Right (truncate d)
    intBytes :: Int -> Int64 -> Either String B.ByteString
    intBytes n i
      | i < lo || i > hi = outOfRange
      | otherwise = Right (littleEndian n (fromIntegral i))
      where
        (lo, hi) = case n of
          1 -> (0, 255)
          2 -> (fromIntegral (minBound :: Int16), fromIntegral (maxBound :: Int16))
          4 -> (fromIntegral (minBound :: Int32), fromIntegral (maxBound :: Int32))
          _ -> (minBound, maxBound)
    outOfRange = Left $ describe v ++ " is out of the range of " ++ T.unpack (typeInfoSqlName ti)

    toBool = \case
      SqlBool b -> Right b
      SqlWord8 i -> Right (i /= 0)
      SqlInt16 i -> Right (i /= 0)
      SqlInt32 i -> Right (i /= 0)
      SqlInt64 i -> Right (i /= 0)
      SqlDecimal d -> Right (d /= 0)
      SqlMoney m -> Right (m /= 0)
      SqlFloat f -> finiteBit f
      SqlDouble d -> finiteBit d
      _ -> mismatch
      where
        finiteBit :: RealFloat a => a -> Either String Bool
        finiteBit n
          | isNaN n || isInfinite n = outOfRange
          | otherwise = Right (n /= 0)

    toDouble :: SqlValue -> Either String Double
    toDouble = \case
      SqlBool b -> Right (if b then 1 else 0)
      SqlWord8 i -> Right (fromIntegral i)
      SqlInt16 i -> Right (fromIntegral i)
      SqlInt32 i -> Right (fromIntegral i)
      SqlInt64 i -> Right (fromIntegral i)
      SqlDecimal d -> Right (fromRational (toRational d))
      SqlMoney m -> Right (realToFrac m)
      SqlFloat f -> Right (float2Double f)
      SqlDouble d -> Right d
      _ -> mismatch

    -- Exact sources must round directly to real's 24-bit precision. An
    -- intermediate Double can erase which side of a Float midpoint they
    -- lie on, so a second rounding chooses the wrong neighbor.
    toFloat :: SqlValue -> Either String Float
    toFloat = \case
      SqlBool b -> Right (if b then 1 else 0)
      SqlWord8 i -> Right (fromIntegral i)
      SqlInt16 i -> Right (fromIntegral i)
      SqlInt32 i -> Right (fromIntegral i)
      SqlInt64 i -> Right (fromIntegral i)
      SqlDecimal d -> Right (fromRational (toRational d))
      SqlMoney m -> Right (fromRational (toRational m))
      SqlFloat f -> Right f
      SqlDouble d -> Right (double2Float d)
      _ -> mismatch

    toMoney :: SqlValue -> Either String Money
    toMoney = \case
      SqlMoney m -> Right m
      SqlBool b -> Right (if b then 1 else 0)
      SqlWord8 i -> Right (fromIntegral i)
      SqlInt16 i -> Right (fromIntegral i)
      SqlInt32 i -> Right (fromIntegral i)
      SqlInt64 i -> Right (fromIntegral i)
      SqlDecimal d -> money <$> rescale 38 4 d
      SqlFloat f -> money <$> roundedFloating 4 f
      SqlDouble d -> money <$> roundedFloating 4 d
      _ -> mismatch
      where
        money (Decimal _ m) = Money (MkFixed m)

    toDecimal :: Scale -> SqlValue -> Either String Decimal
    toDecimal s = \case
      SqlDecimal d -> Right d
      SqlBool b -> Right (if b then 1 else 0)
      SqlWord8 i -> Right (fromIntegral i)
      SqlInt16 i -> Right (fromIntegral i)
      SqlInt32 i -> Right (fromIntegral i)
      SqlInt64 i -> Right (fromIntegral i)
      SqlMoney (Money (MkFixed m)) -> Right (Decimal 4 m)
      SqlFloat f -> roundedFloating s f
      SqlDouble d -> roundedFloating s d
      _ -> mismatch

    -- Scale the exact binary rational, not the floating value: multiplying
    -- in Float or Double first discards low bits, or adds a fractional
    -- tail, even when the value fits the target exactly.  Then round half
    -- away from zero, as the server rounds a float into a decimal (0.125
    -- is 0.13), and as 'rescale' rounds a 'Decimal'.
    roundedFloating :: RealFloat a => Scale -> a -> Either String Decimal
    roundedFloating s n
      | isNaN n || isInfinite n = outOfRange
      | otherwise = Right (Decimal s (halfAwayFromZero (toRational n * 10 ^ s)))
    halfAwayFromZero :: Rational -> Integer
    halfAwayFromZero r = (if r < 0 then negate else id) (if f >= 1 / 2 then q + 1 else q)
      where
        (q, f) = properFraction (abs r)

    -- To the scale, half away from zero (as SQL Server rounds), then
    -- within the precision.
    rescale :: Precision -> Scale -> Decimal -> Either String Decimal
    rescale p s d@(Decimal sc m)
      | digits > fromIntegral p = Left $ describe v ++ " does not fit " ++ T.unpack (typeInfoSqlName ti)
      | otherwise = Right d'
      where
        d'@(Decimal _ m') = if
          | sc == s -> d
          | sc < s -> Decimal s (m * 10 ^ (s - sc))
          | otherwise ->
              let k = 10 ^ (sc - s)
                  (q, r) = abs m `quotRem` k
                  q' = if 2 * r >= k then q + 1 else q
               in Decimal s (signum m * q')
        digits = length (show (abs m'))

    toText = \case
      SqlText t -> Right t
      SqlXml t -> Right t
      _ -> mismatch
    toBinary = \case
      SqlBinary b -> Right b
      _ -> mismatch
    toDay = \case
      SqlDate d -> Right d
      SqlDateTime lt -> Right (localDay lt)
      SqlDateTimeOffset dto -> Right (localDay (dtoLocalTime dto))
      _ -> mismatch
    toTimeOfDay = \case
      SqlTime t -> Right t
      SqlDateTime lt -> Right (localTimeOfDay lt)
      SqlDateTimeOffset dto -> Right (localTimeOfDay (dtoLocalTime dto))
      _ -> mismatch
    toLocalTime = \case
      SqlDateTime lt -> Right lt
      SqlDate d -> Right (LocalTime d midnight)
      SqlDateTimeOffset dto -> Right (dtoLocalTime dto)
      _ -> mismatch
    toDateTimeOffset = \case
      SqlDateTimeOffset dto -> Right dto
      SqlDateTime lt -> Right (DateTimeOffset (localTimeToUTC utc lt) 0)
      SqlDate d -> Right (DateTimeOffset (localTimeToUTC utc (LocalTime d midnight)) 0)
      _ -> mismatch
    dtoLocalTime (DateTimeOffset u mins) = utcToLocalTime (minutesToTimeZone (fromIntegral mins)) u

-- | The value, named for a message.
describe :: SqlValue -> String
describe = \case
  SqlNull -> "NULL"
  SqlBool b -> "the bit " ++ show (fromEnum b)
  SqlWord8 i -> "the integer " ++ show i
  SqlInt16 i -> "the integer " ++ show i
  SqlInt32 i -> "the integer " ++ show i
  SqlInt64 i -> "the integer " ++ show i
  SqlFloat f -> "the real " ++ show f
  SqlDouble d -> "the float " ++ show d
  SqlDecimal d -> "the decimal " ++ show d
  SqlMoney m -> "the money value " ++ show m
  SqlGuid g -> "the uniqueidentifier " ++ show g
  SqlDateTime lt -> "the date-time " ++ show lt
  SqlDate d -> "the date " ++ show d
  SqlTime t -> "the time " ++ show t
  SqlDateTimeOffset dto -> "the datetimeoffset " ++ show (dateTimeOffsetToZonedTime dto)
  SqlText t -> "the string " ++ show (T.take 40 t) ++ (if T.length t > 40 then "..." else "")
  SqlBinary b -> "a binary value of " ++ show (B.length b) ++ " bytes"
  SqlXml _ -> "an xml value"

-- | A @sql_variant@ value carrying the source's own declaration: its base
-- type, precision and scale, length, fixedness and collation, with the
-- bytes as they are.  Going through 'SqlValue' first would widen each to
-- its constructor's canonical type (@smallmoney@ to @money@, @datetime@
-- to @datetime2(7)@, @decimal(38,2)@ to a smaller precision) and replace
-- a lone surrogate.  A source outside the variant's base types (a LOB, a
-- type with no variant form) is decoded and sent as 'variantOf' sends a
-- 'SqlValue'; a UTF-16 LOB that fits goes as a bounded @nvarchar@.
variantFromSource :: TdsContext -> TypeInfo -> B.ByteString -> Either String B.ByteString
variantFromSource ctx source bs = case source of
  _ | Just 4 <- moneyWidth source, B.length bs==4 -> wrap 0x7A B.empty
    | Just n <- dateTimeWidth source, n `elem` [4,8] -> wrap (if n==4 then 0x3A else 0x3D) B.empty
  TIDecimalN p s | p>=1 && p<=38 && s<=p -> wrap 0x6A (B.pack [p,s])
  TINumericN p s | p>=1 && p<=38 && s<=p -> wrap 0x6C (B.pack [p,s])
  TITimeN s -> wrap 0x29 (B.singleton s)
  TIDateTime2N s -> wrap 0x2A (B.singleton s)
  TIDateTimeOffsetN s -> wrap 0x2B (B.singleton s)
  TIBigChar n c | bounded n -> character 0xAF n c
  TIBigVarChar n c | bounded n -> character 0xA7 n c
  TINChar n c | bounded n && even n && even (B.length bs) -> character 0xEF n c
  TINVarChar n c | bounded n && even n && even (B.length bs) -> character 0xE7 n c
  TIBigBinary n | bounded n -> wrap 0xAD (littleEndian 2 (fromIntegral n))
  TIBigVarBinary n | bounded n -> wrap 0xA5 (littleEndian 2 (fromIntegral n))
  -- A UTF-16 LOB that fits goes as a bounded nvarchar, its code units
  -- kept rather than decoded and re-encoded.
  _ | isUnicode source, even (B.length bs), B.length bs<=8000 ->
        character 0xE7 8000 (Collation 0 0)
  _ -> sourceValue source bs >>= variantOf ctx
  where
    bounded n = n>0 && n<=8000 && B.length bs<=fromIntegral n
    wrap base props = do
      -- The bytes are checked as a value of the source type first.
      _ <- sourceValue source bs
      Right (variantBytes base props bs)
    character :: Word8 -> Word16 -> Collation -> Either String B.ByteString
    character base n coll = do
      bytes <- if coll==Collation 0 0
        then maybe (Left "the session's collation isn't known, so a string can't be sent as sql_variant") Right (tdsCollation ctx)
        else Right (runPutSized 5 (putCollation coll))
      wrap base (bytes <> littleEndian 2 (fromIntegral n))
{-# NOINLINE variantFromSource #-}

-- A sql_variant envelope carries its base type and property bytes before
-- the payload (MS-TDS 2.2.5.5.4). A broad SqlValue uses its canonical type;
-- strings use nvarchar in the session collation, with at most 8000 bytes.
--
-- Out of line, as 'variantFromSource' is: a sql_variant column is rare, and
-- inlined at its two call sites in 'encodeBulkCell' its 18 cases were
-- about 10 KB of code each.
variantOf :: TdsContext -> SqlValue -> Either String B.ByteString
variantOf ctx = \case
  SqlBool b -> Right (variant 0x32 B.empty (B.singleton (if b then 1 else 0)))
  SqlWord8 i -> Right (variant 0x30 B.empty (B.singleton i))
  SqlInt16 i -> Right (variant 0x34 B.empty (littleEndian 2 (fromIntegral i)))
  SqlInt32 i -> Right (variant 0x38 B.empty (littleEndian 4 (fromIntegral i)))
  SqlInt64 i -> Right (variant 0x7F B.empty (littleEndian 8 (fromIntegral i)))
  SqlFloat f -> Right (variant 0x3B B.empty (littleEndian 4 (fromIntegral (castFloatToWord32 f))))
  SqlDouble d -> Right (variant 0x3E B.empty (littleEndian 8 (castDoubleToWord64 d)))
  SqlDecimal d@(Decimal s m) -> do
    let p = fromIntegral (max (length (show (abs m))) (fromIntegral s))
    when (p > 38 || s > 38) $ Left ("the decimal " ++ show d ++ " has more than 38 digits")
    Right (variant 0x6A (B.pack [p, s]) (runPutSized 17 (putDecimal p s d)))
  SqlMoney m -> do
    mapM_ Left (money8Problem m)
    Right (variant 0x3C B.empty (runPutSized 8 (putMoney8 m)))
  SqlGuid g -> Right (variant 0x24 B.empty (runPutSized 16 (putGuid g)))
  SqlDateTime lt -> variant 0x2A (B.singleton 7) . runPutSized 8 <$> putDateTime2 7 lt
  SqlDate d -> variant 0x28 B.empty . runPutSized 3 <$> putDate d
  SqlTime t -> variant 0x29 (B.singleton 7) . runPutSized 5 <$> putTime 7 t
  SqlDateTimeOffset dto -> variant 0x2B (B.singleton 7) . runPutSized 10 <$> putDateTimeOffset 7 dto
  SqlText t -> do
    collation <- maybe (Left "the session's collation isn't known, so a string can't be sent as sql_variant") Right (tdsCollation ctx)
    let bs = encodeUtf16LE t
    when (B.length bs > 8000) $ Left "a sql_variant string holds at most 4000 characters"
    Right (variant 0xE7 (collation <> littleEndian 2 8000) bs)
  SqlBinary bs -> do
    when (B.length bs > 8000) $ Left "a sql_variant binary value holds at most 8000 bytes"
    Right (variant 0xA5 (littleEndian 2 8000) bs)
  SqlXml _ -> Left "an xml value can't be sql_variant"
  SqlNull -> Left "NULL"
  where
    variant = variantBytes
{-# NOINLINE variantOf #-}

variantBytes :: Word8 -> B.ByteString -> B.ByteString -> B.ByteString
variantBytes base props value = B.concat [B.pack [base, fromIntegral (B.length props)], props, value]

-- | The low @n@ bytes of the word, little-endian.
littleEndian :: Int -> Word64 -> B.ByteString
littleEndian n w = B.pack [fromIntegral (w `div` (256 ^ i)) | i <- [0 .. n - 1]]

