{-# LANGUAGE MagicHash #-}
-- | Bulk copy: many rows into one table in one request, by the protocol's
-- bulk load (what @bcp@ and .NET's @SqlBulkCopy@ use).  The rows go to the
-- server as a stream of binary values, each in its column's own wire type,
-- with no statement to compile and no parameters to bind, so it is the
-- fastest way to load a table.
--
-- > n <- bulkInsert conn "dbo.item" [(1 :: Int32, "one" :: Text, 9.99 :: Decimal), (2, "two", 0.5)]
--
-- 'bulkInsert' takes any 'ToSqlRow' value per row, asks the server for
-- the table's columns, converts each value to its column's type on the
-- client, and returns the number of rows the server inserted.
-- 'bulkInsertWith' adds the settings ('BulkCopy': which columns, the
-- server's options, batching); 'bulkInsertS' and 'bulkInsertSWith' take
-- the rows from a 'Stream', with defaults or explicit settings.  The rows of a list are streamed too, a packet at a time.
--
-- __Rows.__  A positional row supplies one value per selected column, in
-- the columns' order: under 'InsertableColumns' the table's insertable
-- columns in table order, so a derived 'ToSqlRow' record must follow the
-- table, where an @INSERT@ would name its columns; under 'NamedColumns' the
-- columns named, in that order.  A row with another number of values is an
-- 'EncodeError' naming the row.  A row of 'Hmssql.Encoding.NamedParams'
-- goes to the columns of its names instead, in any order, and must still
-- name every selected column: the one leading @\@@ a name may carry is
-- dropped, so @a@ and @\@a@ both name the column @a@, and @\@\@a@ names a
-- column called @\@a@.
--
-- > data NewItem = NewItem { itemId :: Int, itemName :: Text, itemPrice :: Decimal }
-- >   deriving stock (Generic)
-- >   deriving anyclass (ToSqlRow)
-- >
-- > n <- bulkInsertWith (bulkCopy "dbo.item") { bulkColumns = NamedColumns ["id", "name", "price"] } conn items
--
-- __What the server does with the rows.__  A bulk load skips the checks an
-- @INSERT@ makes unless asked for them: check constraints and foreign
-- keys are not checked ('bulkCheckConstraints'), insert triggers don't
-- fire ('bulkFireTriggers'), and a NULL for a column with a default gets
-- the default ('bulkKeepNulls').  Identity columns are generated by the
-- server unless explicitly selected (for example with 'bulkKeepIdentity').
-- Automatic discovery excludes computed, @rowversion@ and generated-always
-- columns. A failing batch may be rolled
-- back, while earlier batches remain committed; a trigger's @RAISERROR@
-- can report an error without rolling back its rows. Use
-- 'Hmssql.Transaction.withTransaction' for all-or-nothing loading.
--
-- __Types.__  Each value is converted to its column's type as its
-- 'Hmssql.Encoding.ToSqlField' instance sends it ('encodeBulkCell' has the rules).  A value
-- a column can't take (a 'Text' for an @int@ column, a string longer
-- than the column, a character its code page lacks) is an 'EncodeError'
-- naming the row and column, thrown before the row is sent, where a
-- plain @INSERT@ can truncate or transcode it silently.  A 'Double'
-- copied into a @decimal@ or @money@ column is rounded on the client
-- from its exact binary value, half away from zero, as the server rounds
-- it in a parameterized @INSERT@.
--
-- __Permissions.__  An @INSERT@ needs INSERT on the table.  A bulk load
-- also needs SELECT for the column discovery of 'InsertableColumns' and
-- 'NamedColumns' (a @SELECT TOP 0@; 'DescribedColumns' makes no such
-- request), ALTER TABLE when the table has a check constraint or a trigger
-- and 'bulkCheckConstraints' or 'bulkFireTriggers' is off (the server
-- refuses the load with error 5304; with both on, INSERT suffices), and
-- ALTER TABLE for 'bulkKeepIdentity'.  Measured on SQL Server 2025.
--
-- __When an @INSERT@ is the better tool.__  Bulk copy fills a table; for
-- an application's ordinary inserts, 'Hmssql.Query.execute' or
-- 'Hmssql.Query.executeMany' is usually right.  A bulk load has no
-- @OUTPUT@ clause, so generated keys must be queried back; it checks and
-- fires nothing unless asked, and then needs the permissions above; it is
-- one table and whole rows, with no @INSERT ... SELECT@, @MERGE@ or
-- expression; the server answers once per batch, so an error in the first
-- row surfaces after the whole batch is sent; it converts only within a
-- type family where an @INSERT@ converts a string to a number; and a load
-- holds its locks to the end of its transaction.  For a handful of rows,
-- 'Hmssql.Query.executeMany' is nearly as fast and is one round trip where
-- a load with column discovery is two.
--
-- __On a MARS connection__ ('Hmssql.Connection.connectMars') a load works
-- but is a poor neighbor: with a result set open on the connection it
-- fails with error 595 unless @SET XACT_ABORT ON@ is in effect, inside a
-- transaction any other request on the target table fails it with error
-- 3970, and beside busy streams it runs several times slower.  Large
-- loads belong on a connection of their own.
