-- The columns

-- | The columns the rows of a bulk copy hold ('bulkColumns'): as given for
-- 'DescribedColumns'; for the others, asked of the server (@SELECT TOP 0
-- ... FROM@ the table, one round trip).  Each column keeps its real type
-- (a @varchar(50)@ column is a @'TIBigVarChar' 50@, with its collation),
-- which is what 'encodeBulkCell' validates a value against; the load sends
-- it in a wire type ('bulkWireType') the server transcodes from.  Throws
-- 'SqlServerError' for a table or column that doesn't exist.
describeBulkColumns :: Connection -> BulkCopy -> IO [BulkColumn]
describeBulkColumns conn bc = case bulkColumns bc of
  DescribedColumns cols -> pure cols
  NamedColumns names ->
    map fromColumnInfo <$> columnsOf ("SELECT TOP 0 " <> T.intercalate ", " (map quoteName names) <> " FROM " <> bulkTable bc)
  InsertableColumns ->
    map fromColumnInfo . filter insertable <$> columnsOf ("SELECT TOP 0 * FROM " <> bulkTable bc)
  where
    columnsOf sql = do
      cols <- resultColumns <$> queryResultSets (resultSetMWith (pure ())) conn (rawSql sql)
      pure [(c, columnFlags c) | c <- cols]
    -- COLMETADATA flags (MS-TDS 2.2.7.4): fNullable 0x0001, usUpdateable
    -- 0x000C (0 read-only, 4 read/write, 8 unknown), fIdentity 0x0010,
    -- fComputed 0x0020.  A computed, @rowversion@ or generated column is
    -- read-only and never sent; the identity column is read-only too but
    -- is sent when 'bulkKeepIdentity'.
    insertable (_, flags) = not computed && (if identity then bulkKeepIdentity bc else not readonly)
      where
        computed = flags .&. 0x0020 /= 0
        identity = flags .&. 0x0010 /= 0
        readonly = flags .&. 0x000C == 0
    fromColumnInfo (c, flags) = BulkColumn
      { bulkColumnName = columnName c
      , bulkColumnType = columnType c
      , bulkColumnNullable = flags .&. 0x0001 /= 0
      , bulkColumnIdentity = flags .&. 0x0010 /= 0
      }

-- | The wire type a column's values are sent as, which may differ from the
-- column's real type ('bulkColumnType').  Character (@char@, @varchar@,
-- @text@) and @ntext@ columns are sent as @nvarchar(max)@ (UTF-16)
-- and transcoded by the server to the column's own collation on insert (as
-- @bcp -w@ does): correct whatever the collation, where a single-byte value
-- would otherwise be read in the load's default collation, not the
-- column's. @image@ and @xml@ are sent as @varbinary(max)@; XML keeps
-- its byte encoding for the server's parser. Everything else is sent
-- as itself.  'encodeBulkCell' still validates a value against the real type,
-- so a character absent from the column's code page or a value too long is
-- refused on the client, not silently transcoded or truncated by the
-- server.
bulkWireType :: TypeInfo -> TypeInfo
bulkWireType = \case
  TIBigChar _ _ -> TINVarChar maxLength (Collation 0 0)
  TIBigVarChar _ _ -> TINVarChar maxLength (Collation 0 0)
  TIText _ _ -> TINVarChar maxLength (Collation 0 0)
  TINText _ _ -> TINVarChar maxLength (Collation 0 0)
  TIImage _ -> TIBigVarBinary maxLength
  TIXml _ -> TIBigVarBinary maxLength
  ti -> ti

quoteName :: Text -> Text
quoteName n = "[" <> T.replace "]" "]]" n <> "]"

-- | The @INSERT BULK@ statement that announces the load: the table, each
-- column with the type it is sent as, and the options.
insertBulkStatement :: BulkCopy -> [BulkColumn] -> Text
insertBulkStatement bc cols =
  "INSERT BULK " <> bulkTable bc <> " ("
    <> T.intercalate ", " [quoteName (bulkColumnName c) <> " " <> typeInfoSqlName (bulkWireType (bulkColumnType c)) | c <- cols]
    <> ")" <> withClause
  where
    options = concat
      [ ["CHECK_CONSTRAINTS" | bulkCheckConstraints bc]
      , ["FIRE_TRIGGERS" | bulkFireTriggers bc]
      , ["KEEP_NULLS" | bulkKeepNulls bc]
      , ["TABLOCK" | bulkTableLock bc]
      , ["ROWS_PER_BATCH = " <> tshow n | Just n <- [bulkRowsPerBatch bc]]
      , ["KILOBYTES_PER_BATCH = " <> tshow n | Just n <- [bulkKilobytesPerBatch bc]]
      , ["ORDER(" <> T.intercalate ", " (map orderOf (bulkOrder bc)) <> ")" | not (null (bulkOrder bc))]
      ]
    orderOf = \case
      Ascending c -> quoteName c <> " ASC"
      Descending c -> quoteName c <> " DESC"
    withClause
      | null options = ""
      | otherwise = " WITH (" <> T.intercalate ", " options <> ")"
    tshow :: Int -> Text
    tshow = T.pack . show

