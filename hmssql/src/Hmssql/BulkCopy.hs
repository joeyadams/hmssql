-- The message

-- | The COLMETADATA token the load starts with (the same layout the
-- server sends, MS-TDS 2.2.7.4): one token per message, written as a
-- 'Data.Binary.Put.Put'.
colMetaData :: Text -> [BulkColumn] -> B.ByteString
colMetaData table cols = LB.toStrict $ Put.runPut $ do
  Put.putWord8 0x81
  Put.putWord16le (fromIntegral (length cols))
  forM_ cols $ \c -> do
    Put.putWord32le 0  -- UserType
    Put.putWord16le (flagsOf c)
    let wt = bulkWireType (bulkColumnType c)
    putTypeInfo defaultTdsContext wt
    case wt of
      TIText{} -> tableName
      TINText{} -> tableName
      TIImage{} -> tableName
      _ -> pure ()
    putBVarChar (bulkColumnName c)
  where
    -- Nullable, updatable (read/write), identity.
    flagsOf c = (if bulkColumnNullable c then 0x0001 else 0) .|. 0x0004 .|. (if bulkColumnIdentity c then 0x0010 else 0) :: Word16
    tableName = Put.putWord8 1 >> putUsVarChar table

-- | The DONE that ends the load: DONE_FINAL, no count.
doneToken :: B.ByteString
doneToken = B.pack (0xFD : replicate 12 0)

-- | A value in a bulk load ROW.  A PLP type is written with the
-- unknown-length total and 8000-byte chunks ('bulkPlp'); every other
-- type as 'writeValue' writes it.
bulkValue :: TypeInfo -> RawBytes -> BB.Builder
bulkValue ti v = case lengthKind ti of
  Plp -> bulkPlp v
  _ -> writeValue ti v
{-# INLINE bulkValue #-}

-- | A PLP value for a bulk load: NULL as all-ones; otherwise the
-- unknown-length total (@0xFFFFFFFFFFFFFFFE@), the bytes in chunks of at
-- most 'bulkChunk' bytes (each a 4-byte length and its bytes), and a
-- zero-length terminator.  (SQL Server's bulk row parser refuses the
-- known-length total an RPC parameter uses, and refuses chunks longer
-- than 8000 bytes.)
bulkPlp :: RawBytes -> BB.Builder
bulkPlp = \case
  Nothing -> BB.word64LE 0xFFFFFFFFFFFFFFFF
  Just bs -> BB.word64LE 0xFFFFFFFFFFFFFFFE <> chunks bs <> BB.word32LE 0
  where
    chunks b
      | B.null b = mempty
      | otherwise = let (c, rest) = B.splitAt bulkChunk b in BB.word32LE (fromIntegral (B.length c)) <> BB.byteString c <> chunks rest
{-# INLINE bulkPlp #-}

-- | The largest PLP chunk a bulk load sends (SQL Server's limit).
bulkChunk :: Int
bulkChunk = 8000

-- | Write one ROW token.  Consecutive in-memory cells share one Builder, and so
-- one run into the packet buffer, rather than one each.  A lazy or streamed cell
-- flushes what came before it as its prefix before its source runs, so nothing
-- keeps an earlier cell's bytes alive while a source is being read.
writeRow :: PacketWriter -> [TypeInfo] -> [ParamValue] -> IO ()
-- A row whose cells are all in memory and none PLP, the usual kind, is poked into
-- the packet, with its size and its pokes both from 'cellFrame'.  Through a Builder
-- per row it cost about 1,300 bytes and 250 ns per row of an int, an nvarchar(50)
-- and a decimal, in the Builder's closures for each cell, by ticky; the original
-- row walk poked, at 179 bytes and 66 ns.  Strict prefixes for the lengths
-- ('BB.word8' of a computed length, as a 'BP.FixedPrim') saved nothing, and a
-- cheaper 'writeBuilder' could reach only its own 129 bytes per row.  Choosing each
-- column's encoder once per batch, rather than dispatching on its length kind per
-- cell, was measured and rejected: the bulk framing benchmarks allocated 3% more,
-- and their time stayed within the noise.
writeRow out tis values
  | size > 0 = unsafeWriteSized out size $ \p -> pokeByteOff p 0 (0xD1 :: Word8) >> pokeCells p 1 tis values
  | otherwise = go (BB.word8 0xD1) tis values
  where
    size = sized 1 tis values
    -- The row's size if it can be poked, and otherwise 0.
    sized !n (ti : tis') (ParamBytes bytes : values')
      | Plp <- lengthKind ti = 0
      | (width, _, payload) <- cellFrame ti bytes = sized (n + width + B.length payload) tis' values'
    sized n [] [] = n
    sized _ _ _ = 0
    pokeCells p !at (ti : tis') (ParamBytes bytes : values')
      | (width, prefix, payload) <- cellFrame ti bytes = do
          pokePrefix p at width prefix
          -- unsafeWithForeignPtr, as PacketWriter's own copy does: the copy can't
          -- diverge, and unsafeUseAsCString built a closure for keepAlive# per cell.
          case payload of
            BI.BS src n -> BI.unsafeWithForeignPtr src $ \from -> copyBytes (p `plusPtr` (at + width)) from n
          pokeCells p (at + width + B.length payload) tis' values'
    pokeCells _ _ _ _ = pure ()
    pokePrefix p !at !width !prefix
      | width <= 0 = pure ()
      | otherwise = do
          pokeByteOff p at (fromIntegral prefix :: Word8)
          pokePrefix p (at + 1) (width - 1) (prefix `shiftR` 8)
    go prefix (ti : tis') (value : values') = case value of
      ParamBytes bytes -> go (prefix <> bulkValue ti bytes) tis' values'
      _ -> writeParamValueWith out prefix ti value >> go mempty tis' values'
    go prefix _ _ = writeBuilder out prefix

-- | A non-PLP cell held in memory as 'writeValue' writes it: the width in bytes of
-- its length prefix, the prefix's value, little-endian, and the bytes after it.  This
-- is the poked row's one description of a cell, and it must agree with 'writeValue',
-- which "Wire.BulkPacketsSpec" checks.
cellFrame :: TypeInfo -> RawBytes -> (Int, Word64, B.ByteString)
cellFrame ti value = case (lengthKind ti, value) of
  (ByteLen, Nothing) -> (1, 0, B.empty)
  (ByteLen, Just bs) -> (1, len bs, bs)
  (UShortCharBin, Nothing) -> (2, 0xFFFF, B.empty)
  (UShortCharBin, Just bs) -> (2, len bs, bs)
  (LongLen, Nothing) -> (4, 0xFFFFFFFF, B.empty)
  (LongLen, Just bs) -> (4, len bs, bs)
  (VariantLen, Nothing) -> (4, 0, B.empty)
  (VariantLen, Just bs) -> (4, len bs, bs)
  (Fixed _, Just bs) -> (0, 0, bs)
  -- 'NoValue', a NULL of a fixed type (ruled out by 'lengthProblem'), and PLP, which
  -- the caller never pokes, write nothing here.
  _ -> (0, 0, B.empty)
  where len = fromIntegral . B.length
{-# INLINE cellFrame #-}

-- | The packets of a bulk load message for these columns and rows (each
-- row's values converted already, as 'encodeBulkCell' gives them), as
-- 'bulkInsertS' sends them: COLMETADATA, a ROW per row, and the DONE,
-- framed into packets of the context's size.  For tests and benchmarks.
bulkLoadPackets :: TdsContext -> Text -> [BulkColumn] -> [[RawBytes]] -> [B.ByteString]
bulkLoadPackets ctx table cols rows = unsafePerformIO $ do
  acc <- newIORef []
  let tis = map (bulkWireType . bulkColumnType) cols
  runPacketWriter ctx PTBulkLoad (\p -> modifyIORef' acc (p :)) $ \out -> do
    writeBytes out (colMetaData table cols)
    mapM_ (writeRow out tis . map ParamBytes) rows
    writeBytes out doneToken
  reverse <$> readIORef acc
