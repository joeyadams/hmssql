-- Settings

-- | How a bulk copy is done: the table, which of its columns, the
-- server's bulk load options, and batching.  'bulkCopy' has the defaults
-- for a table.
data BulkCopy = BulkCopy
  { bulkTable :: !Text
    -- ^ The table (or view) as SQL names it: @dbo.item@, @[my schema].[t]@,
    -- @#temp@, @db.dbo.t@.  Spliced into the statements as given, so
    -- quote it ('Hmssql.Query.escapeIdentifier' style) if it comes from data.
  , bulkColumns :: !BulkColumns
    -- ^ Which columns the rows hold, and in what order.
  , bulkKeepIdentity :: !Bool
    -- ^ With 'InsertableColumns': send the identity column, with the rows'
    -- values, instead of letting the server generate it.  (A column named
    -- in 'NamedColumns' or given in 'DescribedColumns' is sent as it is.)
    -- The load then needs ALTER TABLE permission on the table.
  , bulkKeepNulls :: !Bool
    -- ^ @KEEP_NULLS@: insert a NULL as NULL where the column has a
    -- default; without it, the default is inserted instead.
  , bulkCheckConstraints :: !Bool
    -- ^ @CHECK_CONSTRAINTS@: check the table's check and foreign key
    -- constraints.  A bulk load skips them by default and leaves them
    -- marked as not trusted (@is_not_trusted@ in @sys.check_constraints@
    -- and @sys.foreign_keys@), which keeps the optimizer from relying on
    -- them until @ALTER TABLE ... WITH CHECK CHECK CONSTRAINT@ re-checks
    -- them; a load with this option keeps the trust.  Without this option
    -- and 'bulkFireTriggers' both, a table that has a check constraint or
    -- a trigger needs ALTER TABLE permission (error 5304).
  , bulkFireTriggers :: !Bool
    -- ^ @FIRE_TRIGGERS@: run the table's insert triggers.
  , bulkTableLock :: !Bool
    -- ^ @TABLOCK@: lock the whole table for the load, which allows
    -- minimal logging and is faster for a large load into a table nobody
    -- else is using.
  , bulkOrder :: ![BulkOrder]
    -- ^ @ORDER(...)@: the rows are sorted by these columns, as the
    -- clustered index is; the server then needn't sort them.  Each batch
    -- must be in that order: a table with a clustered index refuses an
    -- out-of-order batch (error 4819, with or without 'bulkTableLock'),
    -- and a heap ignores the hint.
  , bulkRowsPerBatch :: !(Maybe Int)
    -- ^ @ROWS_PER_BATCH@: about how many rows the load has, for the
    -- query optimizer.
  , bulkKilobytesPerBatch :: !(Maybe Int)
    -- ^ @KILOBYTES_PER_BATCH@: about how much data, likewise.
  , bulkBatchSize :: !(Maybe Int)
    -- ^ Send the rows in batches of this many, each a bulk load of its
    -- own (its own @INSERT BULK@ and round trip), committed on its own
    -- outside a transaction: a failure then loses only its batch's rows,
    -- and the server's memory for the load is bounded.  'Nothing' (the
    -- default): every row in one batch, as one request.
  }

instance Show BulkCopy where
  showsPrec p (BulkCopy a b c e f g h i j k l) = showRecord p "BulkCopy"#
    [ "bulkTable"# := a, "bulkColumns"# := b, "bulkKeepIdentity"# := c, "bulkKeepNulls"# := e
    , "bulkCheckConstraints"# := f, "bulkFireTriggers"# := g, "bulkTableLock"# := h
    , "bulkOrder"# := i, "bulkRowsPerBatch"# := j, "bulkKilobytesPerBatch"# := k
    , "bulkBatchSize"# := l
    ]
  {-# OPAQUE showsPrec #-}

-- | A column of the @ORDER@ hint.
data BulkOrder
  = Ascending !Text
  | Descending !Text

instance Show BulkOrder where
  showsPrec p = \case
    Ascending a -> showCon1 p "Ascending"# a
    Descending a -> showCon1 p "Descending"# a
  {-# OPAQUE showsPrec #-}

instance Eq BulkOrder where
  x == y = case (x, y) of
    (Ascending a, Ascending a') -> eq a a'
    (Descending a, Descending a') -> eq a a'
    _ -> False
  {-# OPAQUE (==) #-}

-- | The defaults for a table: every insertable column, no options, one
-- batch.
bulkCopy :: Text -> BulkCopy
bulkCopy table = BulkCopy
  { bulkTable = table
  , bulkColumns = InsertableColumns
  , bulkKeepIdentity = False
  , bulkKeepNulls = False
  , bulkCheckConstraints = False
  , bulkFireTriggers = False
  , bulkTableLock = False
  , bulkOrder = []
  , bulkRowsPerBatch = Nothing
  , bulkKilobytesPerBatch = Nothing
  , bulkBatchSize = Nothing
  }

-- | Which columns the rows hold.
data BulkColumns
  = InsertableColumns
    -- ^ Every column of the table a plain @INSERT@ without a column list
    -- would take, in table order: all but the identity column (unless
    -- 'bulkKeepIdentity'), computed columns, @rowversion@ and the columns
    -- the server generates.  Asked of the server before the load, with a
    -- @SELECT TOP 0@ that needs SELECT permission on the table.
  | NamedColumns ![Text]
    -- ^ These columns, in this order; the rest get their defaults.  Asked
    -- of the server before the load (their types), so a name that isn't
    -- a column is a 'SqlServerError'.
  | DescribedColumns ![BulkColumn]
    -- ^ These columns, as described: no request to the server before the
    -- load.  For a table loaded many times ('describeBulkColumns' gives
    -- the description once), for a login without SELECT on the table, or
    -- to declare the types the rows are sent in yourself: the server
    -- converts what arrives to the column's type (as an @INSERT@ would,
    -- for a type it converts implicitly), so a @varchar@ column can be
    -- loaded as @nvarchar@, say.
    --
    -- > cols <- describeBulkColumns conn (bulkCopy "dbo.item")
    -- > let settings = (bulkCopy "dbo.item") { bulkColumns = DescribedColumns cols }
    -- > forM_ batches $ \rows -> bulkInsertWith settings conn rows

instance Show BulkColumns where
  showsPrec p = \case
    InsertableColumns -> showString "InsertableColumns"
    NamedColumns a -> showCon1 p "NamedColumns"# a
    DescribedColumns a -> showCon1 p "DescribedColumns"# a
  {-# OPAQUE showsPrec #-}

-- | A column as the bulk load declares it: its name, the wire type the
-- values are sent in (a length, precision and scale, or collation
-- included; 'Hmssql.SqlType.sqlTypeTypeInfo' gives the type of a
-- declaration such as @varchar(20)@), whether a NULL may be sent, and
-- whether it is the table's identity column.
data BulkColumn = BulkColumn
  { bulkColumnName :: !Text
  , bulkColumnType :: !TypeInfo
  , bulkColumnNullable :: !Bool
  , bulkColumnIdentity :: !Bool
  }

instance Show BulkColumn where
  showsPrec p (BulkColumn a b c e) = showRecord p "BulkColumn"#
    [ "bulkColumnName"# := a, "bulkColumnType"# := b, "bulkColumnNullable"# := c
    , "bulkColumnIdentity"# := e
    ]
  {-# OPAQUE showsPrec #-}

instance Eq BulkColumn where
  BulkColumn a b c e == BulkColumn a' b' c' e' = eq a a' && eq b b' && c == c' && e == e'
  {-# OPAQUE (==) #-}

