spec :: Spec
spec = slow $ describe "algorithmic complexity" $ around withTestDb $ do
  describe "number of columns in a row (4x: 1024 vs 4096)" $ do
    it "SqlRow" $ \conn -> do
      let run cnt = do
            (alloc, seen) <- allocatedDuring $ do
              rs <- queryMulti conn (rawSql (manyIntColumns cnt))
              let values = concatMap sqlRowValues (concatMap resultRows rs)
              forceAll values
            seen `shouldBe` cnt
            pure alloc
      small <- run 1024
      large <- run 4096
      subQuadraticAlloc "SqlRow columns" 4 small large

    it "a generic record (256 vs 1024 fields)" $ \conn -> do
      (allocSmall, seenSmall) <- allocatedDuring $ do
        rs <- query conn (rawSql (manyIntColumns 256)) :: IO [Rec256]
        forceAll rs
      seenSmall `shouldBe` 1
      (allocLarge, seenLarge) <- allocatedDuring $ do
        rs <- query conn (rawSql (manyIntColumns 1024)) :: IO [Rec1024]
        forceAll rs
      seenLarge `shouldBe` 1
      subQuadraticAlloc "generic record columns" 4 allocSmall allocLarge

  describe "number of rows (4x: 50,000 vs 200,000)" $
    it "materializing a query" $ \conn -> do
      let run cnt = do
            (alloc, n) <- allocatedDuring $ do
              rows <- (query conn $ rawSql
                ("SELECT TOP " <> tshow cnt <> " ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) \
                 \FROM sys.all_columns a CROSS JOIN sys.all_columns b")) :: IO [Only Int]
              forceAll rows
            n `shouldBe` cnt
            pure alloc
      small <- run 50000
      large <- run 200000
      subQuadraticAlloc "row count" 4 small large

  describe "number of result sets in a batch (4x: 250 vs 1000)" $
    it "queryMulti" $ \conn -> do
      let run cnt = do
            let sql = T.intercalate ";" (replicate cnt "SELECT 1")
            (alloc, n) <- allocatedDuring $ do
              rs <- queryMulti conn (rawSql sql)
              forceAll rs
            n `shouldBe` cnt
            pure alloc
      small <- run 250
      large <- run 1000
      subQuadraticAlloc "result-set count" 4 small large

  describe "number of info (PRINT) messages in a response (8x: 1,000 vs 8,000)" $
    it "delivers all of them to the callback" $ \_ -> do
      countRef <- newIORef (0 :: Int)
      ci <- defaultTestConnectInfo
      withConnection ci { connectOnInfoMessage = \_ -> modifyIORef' countRef (+ 1) } $ \conn -> do
        let run cnt = do
              writeIORef countRef 0
              let sql = T.intercalate ";" (replicate cnt "PRINT 'x'")
              (alloc, ()) <- allocatedDuring (() <$ execute conn (rawSql sql))
              seen <- readIORef countRef
              seen `shouldBe` cnt
              pure alloc
        small <- run 1000
        large <- run 8000
        subQuadraticAlloc "info message count" 8 small large

  describe "number of parameters (4x: 500 vs 2000)" $
    it "encoding" $ \conn -> do
      let run cnt = do
            let params = [SqlParam (i :: Int) | i <- [1 .. cnt]]
                sql = "SELECT " <> T.intercalate "+" ["@p" <> tshow i | i <- [1 .. cnt]]
            (alloc, Only total) <- allocatedDuring (query1 conn (mkQuery sql params) :: IO (Only Int))
            total `shouldBe` sum [1 .. cnt]
            pure alloc
      small <- run 500
      large <- run 2000
      subQuadraticAlloc "parameter count" 4 small large

  describe "parameter size (4x: 1 MiB vs 4 MiB)" $
    it "a single varbinary(max) parameter" $ \conn -> do
      let mib = 1024 * 1024
          run sz = do
            let v = B.replicate sz 0x61
            (alloc, Only len) <- allocatedDuring (query1 conn ("SELECT DATALENGTH(" <> param v <> ")") :: IO (Only Int))
            len `shouldBe` sz
            pure alloc
      small <- run mib
      large <- run (4 * mib)
      subQuadraticAlloc "parameter size" 4 small large

  describe "SQL text length (4x: 100,000 vs 400,000 characters)" $
    it "a plain batch" $ \conn -> do
      let run sz = do
            let sql = "SELECT DATALENGTH(N'" <> T.replicate sz "x" <> "')"
            (alloc, Only len) <- allocatedDuring (query1 conn (rawSql sql) :: IO (Only Int))
            len `shouldBe` 2 * sz
            pure alloc
      small <- run 100000
      large <- run 400000
      subQuadraticAlloc "SQL text length" 4 small large

  describe "number of RETURNVALUE output parameters (10x: 100 vs 1000)" $
    it "callProcedure sorts them by ordinal" $ \conn -> do
      let run :: Int -> IO (Maybe Word64)
          run cnt = do
            name <- uniqueName "hmssql_complexity_outparams"
            let decls = T.intercalate ", " ["@p" <> tshow k <> " int OUTPUT" | k <- [1 .. cnt]]
                sets = T.intercalate "; " ["SET @p" <> tshow k <> " = " <> tshow k | k <- [1 .. cnt]]
            withProc conn name (decls <> " AS BEGIN " <> sets <> " END") $ do
              let params = [outParam ("@p" <> tshow k) (0 :: Int32) | k <- [1 .. cnt]]
              (alloc, res) <- allocatedDuring (callProcedure conn ("dbo." <> name) params)
              let vals = [v | Right (SqlInt32 v) <- map decodeReturnValue (procOutputValues res)]
              vals `shouldBe` map fromIntegral [1 .. cnt]
              pure alloc
      small <- run 100
      large <- run 1000
      subQuadraticAlloc "RETURNVALUE output parameter count" 10 small large

  describe "ENVCHANGE-heavy responses (4x: 1,000 vs 4,000 USE statements)" $
    it "many database-context switches in one batch" $ \conn -> do
      db <- testDatabaseName
      let run cnt = do
            let sql = T.intercalate "; " (take cnt (cycle ["USE tempdb", "USE " <> db]))
            (alloc, ()) <- allocatedDuring (() <$ execute conn (rawSql sql))
            query1 conn "SELECT DB_NAME()" `shouldReturn` Only db
            pure alloc
      small <- run 1000
      large <- run 4000
      subQuadraticAlloc "ENVCHANGE count" 4 small large
