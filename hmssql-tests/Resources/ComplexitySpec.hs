tshow :: Show a => a -> Text
tshow = T.pack . show

-- | Force every element of a (possibly lazily-built) list to whnf: enough to
-- force a record of strict fields fully (all the @RecN@ record fields below
-- are @!Int@), and to force each row's outer structure.
forceAll :: [a] -> IO Int
forceAll = evaluate . List.foldl' (\ !acc x -> x `seq` acc + 1) 0

-- | @SELECT 1,2,...,cnt@: @cnt@ integer columns, one row.
manyIntColumns :: Int -> Text
manyIntColumns cnt = "SELECT " <> T.intercalate "," (map tshow [1 .. cnt])

